"""Publish only measured Full HD Desi scenes and honest static manifests.

The quality report is generated by ffprobe and contains item IDs and dimensions,
never media URLs. Run again with a fresh report after rebuilding Desi data.
"""

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DESI = ROOT / "desi"
CATALOGS = ("desi_bathroom", "desi_couples_viral", "desi_amateur_cuck", "desi_tease_live")
EXCLUDED_TITLE = re.compile(r"\b(?:leak|leaked|college|teen|school|hidden|spy|secret)\b", re.I)


def write_json(path: Path, value: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--quality-report", type=Path, required=True)
    parser.add_argument("--apply", action="store_true")
    args = parser.parse_args()

    report = json.loads(args.quality_report.read_text(encoding="utf-8"))
    measured = report["results"]
    selected = {}
    excluded_content = 0
    for catalog in CATALOGS:
        path = DESI / "catalog" / "movie" / f"{catalog}.json"
        for meta in json.loads(path.read_text(encoding="utf-8")).get("metas", []):
            item_id = meta["id"]
            probe = measured.get(item_id, {})
            width, height = probe.get("width", 0), probe.get("height", 0)
            is_hd = (probe.get("status") == "ok" and
                     max(width, height) >= 1920 and min(width, height) >= 1080)
            if not is_hd:
                continue
            if EXCLUDED_TITLE.search(meta.get("name", "")):
                excluded_content += 1
                continue
            if not (DESI / "stream" / "movie" / f"{item_id}.json").exists():
                continue
            selected.setdefault(item_id, meta)

    items = list(selected.values())
    desi_manifest_path = DESI / "manifest.json"
    desi_manifest = json.loads(desi_manifest_path.read_text(encoding="utf-8"))
    desi_manifest["version"] = "2.261119.1300"
    desi_manifest["name"] = "Desi HD: Verified 1080p+ Adult Scenes"
    desi_manifest["description"] = (
        "Curated adult Desi scenes with directly probed 1080p or better MP4 streams. "
        "Low resolution, unverified, leak-labeled, and age-ambiguous titles are excluded."
    )
    desi_manifest["catalogs"] = [{"type": "movie", "id": "desi_hd", "name": "Desi HD - Verified 1080p+",
                                   "extra": [{"name": "skip", "isRequired": False}]}]

    vidi_manifest_path = ROOT / "manifest.json"
    vidi_manifest = json.loads(vidi_manifest_path.read_text(encoding="utf-8"))
    vidi_manifest["version"] = "9.261119.1300"
    vidi_manifest["name"] = "Vidi 1080p+ Portrait Solo & Creator Suite"
    vidi_manifest["catalogs"] = [c for c in vidi_manifest.get("catalogs", []) if c.get("id") != "vidi_search"]

    print(json.dumps({"measuredUnique": len(measured), "safeHdUnique": len(items),
                      "excludedHdTitles": excluded_content, "desiCatalogsAfter": 1,
                      "vidiCatalogsAfter": len(vidi_manifest["catalogs"]), "apply": args.apply}))
    if not args.apply:
        return
    write_json(DESI / "catalog" / "movie" / "desi_hd.json", {"metas": items})
    write_json(DESI / "catalog" / "movie" / "desi_hd" / "skip=0.json", {"metas": items})
    write_json(desi_manifest_path, desi_manifest)
    write_json(vidi_manifest_path, vidi_manifest)


if __name__ == "__main__":
    main()
